  /// Seeds all snacks, teas, and biscuits into the 'meals' Firestore collection.
  /// Uses document IDs based on the food's barcode to avoid duplicates when re-run.
  static Future<int> seedFoodsDatabase({
    Function(int current, int total)? onProgress,
  }) async {
    final CollectionReference mealsCollection = _firestore.collection('meals');
    final user = FirebaseAuth.instance.currentUser;
    final String currentUserId = user?.uid ?? 'admin_seeder';

    int insertedCount = 0;
    const int chunkSize = 350; // Firestore limit is 500 ops per batch

    for (int i = 0; i < foodCatalog.length; i += chunkSize) {
      final end = (i + chunkSize < foodCatalog.length)
          ? i + chunkSize
          : foodCatalog.length;
      final chunk = foodCatalog.sublist(i, end);
      final WriteBatch batch = _firestore.batch();

      for (final food in chunk) {
        final barcode = (food['barcode'] ?? '').toString();
        // Use predictable ID based on barcode to prevent duplicates
        final docRef = barcode.isNotEmpty
            ? mealsCollection.doc(barcode)
            : mealsCollection.doc();

        final docData = <String, dynamic>{
          ...food,
          'userId': currentUserId,
          'createdAt': FieldValue.serverTimestamp(),
          'updatedAt': FieldValue.serverTimestamp(),
        };

        batch.set(docRef, docData, SetOptions(merge: true));
        insertedCount++;
      }

      await batch.commit();
      onProgress?.call(insertedCount, foodCatalog.length);
      debugPrint("Committed batch: $insertedCount / ${foodCatalog.length} foods");
    }

    return insertedCount;
  }
